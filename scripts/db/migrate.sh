#!/usr/bin/env bash
# Entry point of the Cloud Run job `niho-finance-migrate` (Dockerfile target `migrate`).
#   1. prisma migrate deploy        as the migration role (DATABASE_URL)
#   2. create / update the app role (password taken from NIHO_FINANCE_APP_DATABASE_URL)
#   3. scripts/db/grants.sql        privileges of the app role
# Secrets never reach the log: only role names and migration names are printed.
set -euo pipefail

cd /app/packages/db
echo "[migrate] prisma migrate deploy"
npx --no-install prisma migrate deploy

if [[ -n "${NIHO_FINANCE_APP_DATABASE_URL:-}" ]]; then
  url="$NIHO_FINANCE_APP_DATABASE_URL"
  prefix="postgresql://niho_finance_app:"
  if [[ "$url" != "$prefix"* ]]; then
    echo "[migrate] NIHO_FINANCE_APP_DATABASE_URL must start with ${prefix}" >&2
    exit 1
  fi
  password="${url#"$prefix"}"
  password="${password%%@*}"
  if [[ ! "$password" =~ ^[A-Za-z0-9]+$ ]]; then
    echo "[migrate] the app role password must be alphanumeric (generated by scripts/gcp-bootstrap.sh)" >&2
    exit 1
  fi
  # Cloud SQL: a non-superuser may not even mention (NO)SUPERUSER in ALTER ROLE; the default is NOSUPERUSER.
  echo "[migrate] ensure role niho_finance_app (login, no createdb / createrole)"
  printf '%s\n' \
    "DO \$\$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'niho_finance_app') THEN" \
    "  CREATE ROLE niho_finance_app LOGIN NOCREATEDB NOCREATEROLE;" \
    "END IF; END \$\$;" \
    "ALTER ROLE niho_finance_app WITH LOGIN NOCREATEDB NOCREATEROLE PASSWORD '${password}';" \
    | npx --no-install prisma db execute --stdin --url "$DATABASE_URL" > /dev/null
fi

echo "[migrate] grants"
npx --no-install prisma db execute --file /app/scripts/db/grants.sql --url "$DATABASE_URL"
echo "[migrate] done"
