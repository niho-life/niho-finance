import { describe, expect, it } from "vitest";
import {
  normalizeText,
  parseStatementAmount,
  parseStatementDate,
  parseZenginDate,
} from "../src/csv/fields";

describe("parseStatementDate (12-imports §3.2)", () => {
  it.each([
    ["2026/11/02", "2026-11-02"],
    ["2026-11-02", "2026-11-02"],
    ["2026.11.02", "2026-11-02"],
    ["2026/1/5", "2026-01-05"],
    ["2026-1-5", "2026-01-05"],
    ["2026.1.5", "2026-01-05"],
    ["2026年11月2日", "2026-11-02"],
    ["2026年1月5日", "2026-01-05"],
    ["2026 年 11 月 2 日", "2026-11-02"],
    ["20261102", "2026-11-02"],
    ["R8.11.2", "2026-11-02"],
    ["R08.11.02", "2026-11-02"],
    ["r8/11/2", "2026-11-02"],
    ["R8-11-2", "2026-11-02"],
    ["令和8年11月2日", "2026-11-02"],
    ["令和元年5月1日", "2019-05-01"],
    ["H31.4.30", "2019-04-30"],
    ["平成31年4月30日", "2019-04-30"],
    ["２０２６／１１／０２", "2026-11-02"],
    ["２０２６年１１月２日", "2026-11-02"],
    ["Ｒ８．１１．２", "2026-11-02"],
    ["  2026/11/02  ", "2026-11-02"],
    ["2028/02/29", "2028-02-29"],
  ])("reads %s as %s", (text, expected) => {
    expect(parseStatementDate(text)).toBe(expected);
  });

  it.each([
    "",
    "   ",
    "2026/02/30",
    "2026/13/01",
    "2026/00/10",
    "2026/11/00",
    "2027/02/29",
    "H31.2.29",
    "R8.11.31",
    "R0.1.1",
    "2026/11-02",
    "26/11/02",
    "2026/11/02 10:00",
    "2026-11-02T00:00:00Z",
    "202611021",
    "081102",
    "261102",
    "1102",
    "S60.1.1",
    "昨日",
  ])("rejects %j", (text) => {
    expect(parseStatementDate(text)).toBeNull();
  });
});

describe("parseZenginDate", () => {
  it("takes the year as 令和 (YY + 2018)", () => {
    expect(parseZenginDate("081102")).toBe("2026-11-02");
    expect(parseZenginDate("010501")).toBe("2019-05-01");
    expect(parseZenginDate(" 081231 ")).toBe("2026-12-31");
  });

  it.each(["000101", "081131", "081300", "08110", "0811021", "", "R81102"])(
    "rejects %j",
    (text) => {
      expect(parseZenginDate(text)).toBeNull();
    },
  );
});

describe("parseStatementAmount (12-imports §3.2)", () => {
  it.each([
    ["0", 0n],
    ["1000", 1000n],
    ["1,000", 1000n],
    ["1,234,567", 1234567n],
    ["0000110000", 110000n],
    [" 1 000 ", 1000n],
    ["¥1,000", 1000n],
    ["￥1,000", 1000n],
    ["＼1,000", 1000n],
    ["\\1,000", 1000n],
    ["1,000円", 1000n],
    ["１，０００", 1000n],
    ["+500", 500n],
    ["-500", -500n],
    ["−500", -500n],
    ["－500", -500n],
    ["▲500", -500n],
    ["△500", -500n],
    ["▲ 1,000 円", -1000n],
    ["(500)", -500n],
    ["（1,500）", -1500n],
    ["-¥1,000", -1000n],
    ["¥-1,000", -1000n],
    ["1000.0", 1000n],
    ["1,000.00", 1000n],
    ["-0", 0n],
    ["999999999999999", 999999999999999n],
  ])("reads %j as %s", (text, expected) => {
    expect(parseStatementAmount(text)).toBe(expected);
  });

  it.each([
    "",
    "  ",
    "円",
    "-",
    "1,000.5",
    "1.5",
    "1000.",
    ".0",
    "1,000.000",
    "1,00",
    "10,00",
    "1,0000",
    ",100",
    "--5",
    "+-5",
    "(-5)",
    "-(5)",
    "▲-5",
    "5-",
    "1e3",
    "abc",
    "１２３a",
    "1000000000000000",
  ])("rejects %j", (text) => {
    expect(parseStatementAmount(text)).toBeNull();
  });
});

describe("normalizeText", () => {
  it("trims half-width and full-width spaces and keeps the rest as written", () => {
    expect(normalizeText("　ｶ)ﾃｽﾄ  ")).toBe("ｶ)ﾃｽﾄ");
    expect(normalizeText(" テスト　商事 ")).toBe("テスト　商事");
  });
});
